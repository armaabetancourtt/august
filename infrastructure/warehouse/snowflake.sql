-- Execute with Snowflake admin role after selecting an explicit billing budget.
CREATE DATABASE IF NOT EXISTS AUGUST;
CREATE WAREHOUSE IF NOT EXISTS AUGUST_TRANSFORM WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
CREATE SCHEMA IF NOT EXISTS AUGUST.RAW;
CREATE SCHEMA IF NOT EXISTS AUGUST.ANALYTICS;
CREATE TABLE IF NOT EXISTS AUGUST.RAW.PROPERTY_EVENTS (
 EVENT_ID VARCHAR NOT NULL, PROPERTY_ID VARCHAR NOT NULL,
 OCCURRED_AT TIMESTAMP_NTZ NOT NULL, AMOUNT NUMBER(18,2) NOT NULL, EVENT_TYPE VARCHAR NOT NULL
);
